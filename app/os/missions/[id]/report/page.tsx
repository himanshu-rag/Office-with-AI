'use client';
import { useEffect, useState, use } from 'react';
import { Share, CheckCircle, WarningCircle, User } from '@phosphor-icons/react';

export default function MissionReportPage({ params }: { params: Promise<{ id: string }> }) {
  const { id } = use(params);
  const [data, setData] = useState<any>(null);

  useEffect(() => {
    fetch(`/api/os/missions/${id}/report`)
      .then(res => res.json())
      .then(setData);
  }, [id]);

  if (!data) return <div className="p-8 text-white">Loading report...</div>;
  if (data.error) return <div className="p-8 text-red-500">Error: {data.error}</div>;

  const { mission, tasks, company } = data;

  return (
    <div className="min-h-screen bg-white text-zinc-900 font-sans p-8 md:p-16 selection:bg-indigo-100">
      <div className="max-w-4xl mx-auto space-y-16">
        
        {/* Header */}
        <header className="flex items-end justify-between border-b border-zinc-200 pb-8">
          <div>
            <div className="flex items-center gap-3 mb-4">
              <span className="px-3 py-1 bg-indigo-50 text-indigo-700 rounded-full text-xs font-bold uppercase tracking-widest border border-indigo-100">
                Official Report
              </span>
              <span className="text-sm text-zinc-500 font-medium">{new Date(mission.completed_at || mission.created_at || Date.now()).toLocaleDateString()}</span>
            </div>
            <h1 className="text-4xl font-extrabold tracking-tight mb-2">{mission.title}</h1>
            <p className="text-lg text-zinc-600 max-w-2xl">{mission.objective}</p>
          </div>
          <div className="text-right">
            <p className="text-sm font-bold text-zinc-400 uppercase tracking-widest mb-1">Prepared For</p>
            <p className="text-xl font-bold">{company?.name || 'Company'}</p>
            <p className="text-sm text-zinc-500 capitalize">{company?.type || 'AI-Powered Business'}</p>
          </div>
        </header>

        {/* CEO Strategy */}
        <section className="bg-zinc-50 rounded-3xl p-8 border border-zinc-200">
          <h2 className="text-sm font-bold text-zinc-400 uppercase tracking-widest mb-4">CEO Strategic Plan</h2>
          <div className="text-base text-zinc-700 leading-relaxed whitespace-pre-wrap">
            {mission.ceo_plan || 'No strategic plan recorded.'}
          </div>
        </section>

        {/* Task Outputs */}
        <section>
          <h2 className="text-sm font-bold text-zinc-400 uppercase tracking-widest mb-8 border-b border-zinc-200 pb-4">Execution Log</h2>
          <div className="space-y-12">
            {tasks.map((task: any, i: number) => (
              <div key={task.id} className="relative pl-8">
                <div className="absolute left-0 top-1.5 bottom-0 w-px bg-zinc-200" />
                <div className="absolute left-[-4px] top-2 w-2 h-2 rounded-full bg-indigo-500 ring-4 ring-white" />
                
                <div className="mb-2 flex items-center gap-3">
                  <h3 className="text-xl font-bold">{i + 1}. {task.title}</h3>
                  <span className={`flex items-center gap-1 text-xs font-bold px-2 py-0.5 rounded-full ${task.state === 'completed' ? 'bg-green-100 text-green-700' : 'bg-red-100 text-red-700'}`}>
                    {task.state === 'completed' ? <CheckCircle weight="fill" /> : <WarningCircle weight="fill" />}
                    {task.state}
                  </span>
                </div>
                
                <div className="flex items-center gap-2 mb-4">
                  <div className="flex items-center gap-1.5 px-2.5 py-1 bg-zinc-100 rounded-lg border border-zinc-200">
                    <span className="text-sm">{task.avatar_emoji || '🤖'}</span>
                    <span className="text-xs font-bold text-zinc-600">{task.agent_name || 'Unassigned'}</span>
                  </div>
                </div>

                <div className="bg-white rounded-2xl p-6 border border-zinc-200 shadow-sm text-sm text-zinc-800 leading-relaxed whitespace-pre-wrap">
                  {task.output || 'No output recorded.'}
                </div>
              </div>
            ))}
          </div>
        </section>

        <footer className="text-center pt-16 pb-8 text-sm text-zinc-400">
          <p>Generated by AI Company OS</p>
        </footer>
      </div>
    </div>
  );
}
